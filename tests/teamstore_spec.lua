local T = require('tests.lib.t')
dofile(ROOT .. '/shared/teamstore.lua')

T.describe('TeamStore create / join', function()
    T.it('creates a team led by its creator', function()
        local store = TeamStore.new(4)
        local team = store:create(1)
        T.eq(team.leader, 1)
        T.eq(team.members, { 1 })
        T.eq(store:teamOf(1), team)
    end)

    T.it('refuses a second team for the same player', function()
        local store = TeamStore.new(4)
        store:create(1)
        T.eq({ store:create(1) }, { nil, 'You are already in a team' })
    end)

    T.it('joins up to the maximum size', function()
        local store = TeamStore.new(2)
        local team = store:create(1)
        T.eq(store:join(2, team.id), team)
        T.eq(team.members, { 1, 2 })
        T.eq({ store:join(3, team.id) }, { nil, 'That team is full' })
    end)

    T.it('refuses joining a missing, busy or own team', function()
        local store = TeamStore.new(4)
        local team = store:create(1)
        T.eq({ store:join(2, 999) }, { nil, 'That team no longer exists' })
        T.eq({ store:join(1, team.id) }, { nil, 'You are already in a team' })
        store:setBusy(team.id, true)
        T.eq({ store:join(2, team.id) }, { nil, 'That team is already working' })
    end)

    T.it('lists only teams that can still be joined', function()
        local store = TeamStore.new(2)
        local open = store:create(1)
        local full = store:create(2)
        store:join(3, full.id)
        local busy = store:create(4)
        store:setBusy(busy.id, true)
        local list = store:openTeams()
        T.eq(#list, 1)
        T.eq(list[1].id, open.id)
    end)
end)

T.describe('TeamStore leave / kick', function()
    T.it('hands the team to the next member when the leader leaves', function()
        local store = TeamStore.new(4)
        local team = store:create(1)
        store:join(2, team.id)
        store:join(3, team.id)
        local result = store:leave(1)
        T.eq(result.newLeader, 2)
        T.eq(result.disbanded, false)
        T.eq(team.leader, 2)
        T.eq(team.members, { 2, 3 })
        T.eq(store:teamOf(1), nil)
    end)

    T.it('disbands the team when the last member leaves', function()
        local store = TeamStore.new(4)
        local team = store:create(1)
        local result = store:leave(1)
        T.eq(result.disbanded, true)
        T.eq(store:get(team.id), nil)
    end)

    T.it('returns nil when leaving without a team', function()
        T.eq(TeamStore.new(4):leave(5), nil)
    end)

    T.it('lets only the leader kick other members', function()
        local store = TeamStore.new(4)
        local team = store:create(1)
        store:join(2, team.id)
        store:join(3, team.id)
        T.eq({ store:kick(2, 3) }, { nil, 'Only the team leader can do that' })
        T.eq({ store:kick(1, 1) }, { nil, 'Use Leave to quit your own team' })
        T.eq({ store:kick(1, 9) }, { nil, 'That player is not in your team' })
        T.eq(store:kick(1, 3), true)
        T.eq(team.members, { 1, 2 })
        T.eq(store:teamOf(3), nil)
    end)
end)
